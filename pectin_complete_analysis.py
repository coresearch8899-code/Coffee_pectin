def pareto(d, maxc, minc):
    """True for rows not dominated by any other row (maximise maxc, minimise minc)."""
    keep = []
    for i, a in d.iterrows():
        dom = any(all(b[c] >= a[c] for c in maxc) and all(b[c] <= a[c] for c in minc) and
                  (any(b[c] > a[c] for c in maxc) or any(b[c] < a[c] for c in minc)) for j, b in d.iterrows() if j != i)
        keep.append(not dom)
    return np.array(keep)
